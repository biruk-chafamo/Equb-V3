from typing import Any, Optional, Protocol


class Notifier(Protocol):
    def equb_created(self, equb: Any) -> None: ...

    def member_joined(self, equb: Any, new_member: Any) -> None: ...

    def equb_activated(self, equb: Any) -> None: ...

    def bid_outbid(self, equb: Any, previous_highest_bid: Optional[Any], new_highest_bid: Any) -> None: ...

    def round_advanced(self, equb: Any) -> None: ...

    def payment_confirmation_requested(self, payment_confirmation_request: Any) -> None: ...

    def join_request_created(self, join_request: Any) -> None: ...

    def join_request_voted(self, join_request: Any) -> None: ...
